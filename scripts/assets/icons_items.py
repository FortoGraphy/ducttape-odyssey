GLYPH_SLOT = {"x": "6", "h": "7", "d": "5"}


def _hash(text: str) -> int:
    return zlib.crc32(text.encode("utf-8"))


def _rows(template: str) -> list[str]:
    return [r.strip() for r in T[template].strip("\n").split("\n")]


def _ramp(ramp) -> tuple[str, str, str, str]:
    return RAMPS[ramp] if isinstance(ramp, str) else ramp


def _legend(ramp, ramp2) -> dict[str, str]:
    r, s = _ramp(ramp), _ramp(ramp2)
    table = dict(EXTRA)
    table.update({"1": r[0], "2": r[1], "3": r[2], "4": r[3], "5": s[1], "6": s[2], "7": s[3], "8": s[0]})
    return table


def _finish(grid: list[str], legend: dict[str, str]) -> Image.Image:
    """Grid -> outlined icon, with the art centered in the cell so mixed templates line up in lists."""
    art = icons_lib.parse(grid, legend=legend, outline=None)
    box = art.getchannel("A").getbbox()
    if box is None:
        return art
    w, h = box[2] - box[0], box[3] - box[1]
    out = Image.new("RGBA", art.size, (0, 0, 0, 0))
    out.paste(art.crop(box), ((icons_lib.SIZE - w) // 2, (icons_lib.SIZE - h) // 2))
    return icons_lib.add_outline(out)


def render(template: str, ramp="steel", ramp2=None) -> Image.Image:
    return _finish(_rows(template), _legend(ramp, ramp2 or "steel"))


def _hashed(pool: list[str], key: str, salt: int) -> Image.Image:
    h = _hash(f"{key}#{salt}")
    pool = [t for t in pool if t in T]
    template = pool[h % len(pool)]
    ramp = FALLBACK_RAMPS[(h >> 8) % len(FALLBACK_RAMPS)]
    ramp2 = FALLBACK_RAMPS[(h >> 16) % len(FALLBACK_RAMPS)]
    return render(template, ramp, ramp2)


def _module(item: dict, salt: int = 0) -> Image.Image:
    tags = item.get("tags") or []
    family = item.get("family") or next((t for t in tags if t in FAMILY), "")
    try:
        mk = max(1, min(5, int(item.get("mk") or 1)))
    except (TypeError, ValueError):
        mk = 1
    special = "special" in tags or item["id"] != f"mod_{family}_mk{mk}" or salt > 0
    if family in FAMILY:
        glyph, accent = FAMILY[family]
    else:
        glyph, accent = "generic", FALLBACK_RAMPS[_hash(family or item["id"]) % len(FALLBACK_RAMPS)]
    if special:
        glyph = SPECIAL_GLYPH.get(item["id"], glyph)
        frame, template, origin = SPECIAL_FRAMES[salt % len(SPECIAL_FRAMES)], "mod_frame_special", (4, 4)
    else:
        frame, template, origin = MK_FRAME[mk - 1], "mod_frame", (3, 3)

    grid = [list(r) for r in _rows(template)]
    for gy, row in enumerate(GLYPHS[glyph].strip("\n").split("\n")):
        for gx, ch in enumerate(row.strip()):
            if ch != ".":
                grid[origin[1] + gy][origin[0] + gx] = GLYPH_SLOT.get(ch, ch)
    # Pip slots light up bottom-to-top on the side column, left-to-right on the special frame's row.
    cells = [(x, y) for y, row in enumerate(grid) for x, ch in enumerate(row) if ch == "P"]
    slots = sorted({y for _, y in cells}, reverse=True) if template == "mod_frame" else sorted({x for x, _ in cells})
    for x, y in cells:
        index = slots.index(y if template == "mod_frame" else x)
        grid[y][x] = "6" if index < mk else "s"
    return _finish(["".join(r) for r in grid], _legend(frame, accent))


def _item(item: dict, salt: int = 0) -> Image.Image:
    if item.get("category") == "module":
        return _module(item, salt)
    art = ITEM_ART.get(item["id"])
    if art and salt == 0:
        return render(*art)
    cat = item.get("category", "raw")
    pool = FALLBACK.get(cat) or FALLBACK["raw"]
    if cat == "mega" and "frame" in (item.get("tags") or []):
        pool = FALLBACK["mega:frame"]
    return _hashed(pool, item["id"], salt)


def _lighter(key: str) -> str:
    for ramp in RAMPS.values():
        if key in ramp[:3]:
            return ramp[ramp.index(key) + 1]
    return "bone2"


def _color_ramp(key: str):
    """A 4-step ramp whose body color is the given palette key (None if it is not a palette key)."""
    if key not in pal.RGB:
        return None
    for ramp in RAMPS.values():
        if ramp[2] == key:
            return ramp
    dark = pal.DARKER.get(key, "void3")
    return (pal.DARKER.get(dark, "void1"), dark, key, _lighter(key))


def _cosmetic(cos: dict, salt: int = 0) -> Image.Image:
    kind, cid = cos.get("kind"), cos["id"]
    if kind in ("paint", "trail"):
        ramp = _color_ramp(str(cos.get("value"))) if salt == 0 else None
        if ramp is None:
            ramp = FALLBACK_RAMPS[_hash(f"{cid}#{salt}") % len(FALLBACK_RAMPS)]
        return render("paint_can" if kind == "paint" else "trail", ramp)
    art = COSMETIC_ART.get(cid)
    if art and salt == 0:
        return render(*art)
    return _hashed(FALLBACK["toy" if kind == "toy" else "sticker"], cid, salt)


def _unique(make, seen: set[bytes]) -> Image.Image:
    """First salt whose pixels nobody else has. Table art is salt 0; higher salts re-roll the hash."""
    img = make(0)
    for salt in range(1, 48):
        if img.tobytes() not in seen:
            break
        img = make(salt)
    else:
        # Last resort for pathological inputs: stamp a counter as palette pixels along the bottom row.
        n, base = len(seen), img
        while img.tobytes() in seen:
            img = base.copy()
            for bit in range(8):
                img.putpixel((4 + bit, 15), pal.c("amber" if n >> bit & 1 else "void3"))
            n += 1
    seen.add(img.tobytes())
    return img


def build_item_icons(manifest: dict) -> dict[str, Image.Image]:
    """One outlined 16x16 RGBA icon per item id and per cosmetic id. Deterministic."""
    icons: dict[str, Image.Image] = {}
    seen: set[bytes] = set()
    for item in manifest.get("items", []):
        icons[item["id"]] = _unique(lambda salt, it=item: _item(it, salt), seen)
    for cos in manifest.get("cosmetics", []):
        if cos["id"] not in icons:
            icons[cos["id"]] = _unique(lambda salt, c=cos: _cosmetic(c, salt), seen)
    return icons


def check_templates() -> list[str]:
    """Human-readable problems in the grids and tables (sizes, borders, unknown names or characters)."""
    bad = []
    known = set(icons_lib.LEGEND) | set(EXTRA) | set("12345678P")
    for name in T:
        rows = _rows(name)
        if len(rows) != 16:
            bad.append(f"{name}: {len(rows)} rows")
        for y, row in enumerate(rows):
            if len(row) != 16:
                bad.append(f"{name} row {y}: {len(row)} chars: {row!r}")
            elif (y in (0, 15) and row.strip(".")) or row[0] != "." or row[-1] != ".":
                bad.append(f"{name} row {y}: art outside the 14x14 interior: {row!r}")
            if set(row) - known:
                bad.append(f"{name} row {y}: unknown characters {sorted(set(row) - known)}")
    for name, glyph in GLYPHS.items():
        rows = [r.strip() for r in glyph.strip("\n").split("\n")]
        if len(rows) != 7 or any(len(r) != 7 for r in rows):
            bad.append(f"glyph {name}: must be 7x7")
    for table in (ITEM_ART, COSMETIC_ART):
        for key, art in table.items():
            if art[0] not in T:
                bad.append(f"{key}: unknown template {art[0]}")
            bad += [f"{key}: unknown ramp {r}" for r in art[1:] if r not in RAMPS]
    for cat, pool in FALLBACK.items():
        bad += [f"fallback {cat}: unknown template {t}" for t in pool if t not in T]
    for fam, (glyph, ramp) in FAMILY.items():
        if glyph not in GLYPHS or ramp not in RAMPS:
            bad.append(f"family {fam}: unknown glyph or ramp")
    bad += [f"special glyph {g} missing" for g in SPECIAL_GLYPH.values() if g not in GLYPHS]
    return bad


def self_check(manifest: dict) -> str:
    """Asserts the contract (coverage, size, binary alpha, palette-only, no duplicates, determinism)."""
    problems = check_templates()
    assert not problems, problems
    icons = build_item_icons(manifest)
    again = build_item_icons(manifest)
    wanted = [i["id"] for i in manifest.get("items", [])] + [c["id"] for c in manifest.get("cosmetics", [])]
    missing = [k for k in wanted if k not in icons]
    assert not missing, f"no icon for {missing}"
    untabled = [i["id"] for i in manifest.get("items", []) if i.get("category") != "module" and i["id"] not in ITEM_ART]
    untabled += [c["id"] for c in manifest.get("cosmetics", []) if c.get("kind") in ("sticker", "toy") and c["id"] not in COSMETIC_ART]

    def verify(batch: dict[str, Image.Image]) -> None:
        owner: dict[bytes, str] = {}
        for key, img in batch.items():
            assert img.mode == "RGBA" and img.size == (16, 16), f"{key}: {img.mode} {img.size}"
            assert set(img.getchannel("A").tobytes()) <= {0, 255}, f"{key}: alpha is not binary"
            assert pal.off_palette(img) == 0, f"{key}: off-palette pixels"
            assert img.getchannel("A").getbbox() is not None, f"{key}: empty icon"
            twin = owner.setdefault(img.tobytes(), key)
            assert twin == key, f"{key} is pixel-identical to {twin}"

    verify(icons)
    assert all(icons[k].tobytes() == again[k].tobytes() for k in icons), "output is not deterministic"

    # Content that does not exist yet must still get valid, distinct icons.
    future = {"items": list(manifest.get("items", [])), "cosmetics": list(manifest.get("cosmetics", []))}
    for cat in ("raw", "refined", "component", "mega", "consumable", "artifact", "special", "unheard_of"):
        future["items"] += [{"id": f"zz_{cat}_{n}", "tier": 1, "category": cat, "tags": []} for n in range(6)]
    future["items"] += [{"id": f"zz_frame_{n}", "tier": 4, "category": "mega", "tags": ["frame"]} for n in range(3)]
    future["items"] += [{"id": f"mod_laser_mk{n}", "category": "module", "tags": ["laser"], "family": "laser", "mk": n} for n in (6, 7)]
    future["items"] += [{"id": f"mod_zz_mk{n}", "category": "module", "tags": ["zz"], "family": "zz", "mk": n} for n in (1, 2)]
    future["items"] += [{"id": f"mod_zz_odd_{n}", "category": "module", "tags": ["cargo", "special"], "family": "cargo", "mk": 3} for n in range(9)]
    future["items"] += [{"id": "mod_bare", "category": "module"}]
    for kind in ("paint", "trail"):
        future["cosmetics"] += [{"id": f"{kind}_zz_{n}", "kind": kind, "value": v} for n, v in enumerate(("teal2", "nope", "steel0", "void3", None))]
    for kind in ("sticker", "toy", "hat"):
        future["cosmetics"] += [{"id": f"{kind}_zz_{n}", "kind": kind, "value": f"{kind}_zz_{n}"} for n in range(4)]
    grown = build_item_icons(future)
    assert len(grown) == len(future["items"]) + len(future["cosmetics"])
    verify(grown)
    assert all(grown[k].tobytes() == icons[k].tobytes() for k in icons), "new content changed existing icons"

    note = f", {len(untabled)} ids on hashed fallback: {untabled}" if untabled else ""
    return f"ok: {len(icons)} icons, {len(T)} templates, {len(GLYPHS)} glyphs, {len(RAMPS)} ramps{note}"
